using System.IO;
using System.Windows.Media;

namespace Semojum.Desktop.Controls;

/// <summary>Absolute file references also work inside an anonymous WPF composite font's FamilyMaps.</summary>
public static class BundledFonts
{
    public static Uri DirectoryUri { get; } = new(Path.Combine(AppContext.BaseDirectory, "Assets", "Fonts") + Path.DirectorySeparatorChar);
    private static string Location => DirectoryUri.AbsoluteUri.Replace(",", "%2C", StringComparison.Ordinal);
    // Ship the font so Korean and Latin text use the same family on every PC.
    public static FontFamily Interface { get; } = new($"{Location}#Pretendard");
    public static FontFamily UserInterface => Interface;
    public static FontFamily Mono => Interface;
    public static FontFamily Braille { get; } = CreateBraille();
    // IMM uses GDI, which cannot resolve WPF's file URI. These fonts are private
    // to this process and are released by Windows when the app exits.
    public static void RegisterNativeInputFonts()
    {
        foreach (var file in Directory.EnumerateFiles(DirectoryUri.LocalPath, "Pretendard-*.ttf"))
            AddFontResourceExW(file, 0x10, IntPtr.Zero);
    }
    [System.Runtime.InteropServices.DllImport("gdi32.dll", CharSet = System.Runtime.InteropServices.CharSet.Unicode)]
    private static extern int AddFontResourceExW(string file, uint flags, IntPtr reserved);
    /// <summary>Nuridot Braille (generated by scripts/build-braille-font.py) holds only braille cells and blanks, so it maps just those;
    /// all other text, such as line numbers and layout markers, uses Pretendard.</summary>
    private static FontFamily CreateBraille()
    {
        var nuridot = new FontFamily($"{Location}#Nuridot Braille");
        var family = new FontFamily { LineSpacing = nuridot.LineSpacing, Baseline = nuridot.Baseline };
        family.FamilyMaps.Add(new FontFamilyMap { Unicode = "0020,00A0,2800-28FF", Target = $"{Location}#Nuridot Braille, Segoe UI Symbol" });
        family.FamilyMaps.Add(new FontFamilyMap { Unicode = "0000-10FFFF", Target = Interface.Source });
        return family;
    }
}
